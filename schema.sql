CREATE OR REPLACE FUNCTION maintain_log_partitions(months_ahead integer DEFAULT 14)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    month_start date;
    partition_name text;
    i integer;
BEGIN
    IF months_ahead < 2 OR months_ahead > 36 THEN
        RAISE EXCEPTION 'months_ahead must be between 2 and 36';
    END IF;
    FOR i IN 0..months_ahead LOOP
        month_start := date_trunc('month', current_date)::date + make_interval(months => i);
        partition_name := 'communication_log_' || to_char(month_start, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF communication_log FOR VALUES FROM (%L) TO (%L)',
            partition_name, month_start, (month_start + interval '1 month')::date
        );
        partition_name := 'audit_log_' || to_char(month_start, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS %I PARTITION OF audit_log FOR VALUES FROM (%L) TO (%L)',
            partition_name, month_start, (month_start + interval '1 month')::date
        );
    END LOOP;
END;
$$;
SELECT maintain_log_partitions(14);

CREATE OR REPLACE FUNCTION audit_row_change()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_row jsonb;
    new_row jsonb;
    row_data jsonb;
    entity_key text;
    fields text[];
    actor uuid;
    tenant_id text;
    branch_key text;
    patient_key text;
    appointment_key text;
BEGIN
    old_row := CASE WHEN TG_OP IN ('UPDATE','DELETE') THEN to_jsonb(OLD) ELSE '{}'::jsonb END;
    new_row := CASE WHEN TG_OP IN ('INSERT','UPDATE') THEN to_jsonb(NEW) ELSE '{}'::jsonb END;
    row_data := CASE WHEN TG_OP = 'DELETE' THEN old_row ELSE new_row END;
    entity_key := coalesce(row_data->>'id', row_data->>'patient_id', row_data->>'appointment_id',
                           row_data->>'visit_id', row_data->>'invoice_id', row_data->>'prescription_id', 'unknown');
    IF TG_OP = 'INSERT' THEN
        SELECT coalesce(array_agg(k ORDER BY k), '{}') INTO fields FROM jsonb_object_keys(new_row) AS keys(k);
    ELSIF TG_OP = 'DELETE' THEN
        SELECT coalesce(array_agg(k ORDER BY k), '{}') INTO fields FROM jsonb_object_keys(old_row) AS keys(k);
    ELSE
        SELECT coalesce(array_agg(n.key ORDER BY n.key), '{}') INTO fields
        FROM jsonb_each(new_row) n
        FULL JOIN jsonb_each(old_row) o USING (key)
        WHERE n.value IS DISTINCT FROM o.value;
    END IF;
    actor := nullif(current_setting('app.user_id', true), '')::uuid;
    tenant_id := row_data->>'organisation_id';
    branch_key := row_data->>'branch_id';
    patient_key := row_data->>'patient_id';
    appointment_key := row_data->>'appointment_id';
    IF tenant_id IS NULL AND branch_key IS NOT NULL THEN
        SELECT organisation_id::text INTO tenant_id FROM branches WHERE id = branch_key::uuid;
    END IF;
    IF tenant_id IS NULL AND patient_key IS NOT NULL THEN
        SELECT organisation_id::text INTO tenant_id FROM patients WHERE id = patient_key::uuid;
    END IF;
    IF appointment_key IS NULL THEN
        appointment_key := row_data->>'id';
        IF TG_TABLE_NAME IN ('appointments','call_attempts','appointment_events') THEN
            appointment_key := coalesce(row_data->>'id', row_data->>'appointment_id');
        ELSE
            appointment_key := NULL;
        END IF;
    END IF;
    IF tenant_id IS NULL AND appointment_key IS NOT NULL THEN
        SELECT b.organisation_id::text, b.id::text INTO tenant_id, branch_key
        FROM appointments a JOIN branches b ON b.id = a.branch_id
        WHERE a.id = appointment_key::uuid;
    END IF;
    IF tenant_id IS NULL AND row_data->>'user_id' IS NOT NULL THEN
        SELECT organisation_id::text INTO tenant_id FROM users WHERE id = (row_data->>'user_id')::uuid;
    END IF;
    INSERT INTO audit_log(actor_id, action, entity_type, entity_id, changed_fields)
    VALUES (actor, lower(TG_OP), TG_TABLE_NAME, entity_key, fields);
    IF tenant_id IS NOT NULL THEN
        PERFORM pg_notify('crm_events', json_build_object(
            'entity', TG_TABLE_NAME, 'id', entity_key, 'action', lower(TG_OP),
            'organisation_id', tenant_id, 'branch_id', branch_key
        )::text);
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

CREATE OR REPLACE FUNCTION record_audit_view(p_entity_type text, p_entity_id text, p_request_id text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    actor uuid;
BEGIN
    actor := nullif(current_setting('app.user_id', true), '')::uuid;
    IF actor IS NULL THEN
        RAISE EXCEPTION 'authenticated actor required for view audit';
    END IF;
    INSERT INTO audit_log(actor_id, action, entity_type, entity_id, request_id)
    VALUES (actor, 'view', p_entity_type, p_entity_id, p_request_id);
END;
$$;

