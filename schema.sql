-- Dental hospital CRM schema for PostgreSQL 16+.
-- Clinical, financial, communication, and audit history is retained; corrections are additive.
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS schema_migrations (
    version text PRIMARY KEY,
    checksum text NOT NULL CHECK (checksum ~ '^[a-f0-9]{64}$'),
    applied_at timestamptz NOT NULL DEFAULT now(),
    applied_by name NOT NULL DEFAULT current_user
);

CREATE TABLE IF NOT EXISTS organisations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL,
    country_code char(2) NOT NULL DEFAULT 'IN',
    timezone text NOT NULL DEFAULT 'Asia/Kolkata',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS branches (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organisation_id uuid NOT NULL REFERENCES organisations(id),
    name text NOT NULL,
    address text NOT NULL DEFAULT '',
    city text NOT NULL DEFAULT '',
    country_code char(2) NOT NULL DEFAULT 'IN',
    timezone text NOT NULL DEFAULT 'Asia/Kolkata',
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organisation_id, name)
);

CREATE TABLE IF NOT EXISTS rooms (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    branch_id uuid NOT NULL REFERENCES branches(id),
    name text NOT NULL,
    room_type text NOT NULL DEFAULT 'chair',
    is_active boolean NOT NULL DEFAULT true,
    UNIQUE (branch_id, name)
);

CREATE TABLE IF NOT EXISTS roles (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (name IN ('admin','telecaller','receptionist','dentist','accountant')),
    description text NOT NULL DEFAULT ''
);

INSERT INTO roles (name, description) VALUES
    ('admin','Clinic administration'),
    ('telecaller','Patient calls and appointment requests'),
    ('receptionist','Front desk and appointments'),
    ('dentist','Clinical records and treatment'),
    ('accountant','Estimates, invoices and payments')
ON CONFLICT (name) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    organisation_id uuid NOT NULL REFERENCES organisations(id),
    branch_id uuid REFERENCES branches(id),
    full_name text NOT NULL,
    email text NOT NULL,
    password_hash text NOT NULL,
    preferred_language text NOT NULL DEFAULT 'en',
    is_active boolean NOT NULL DEFAULT true,
    soft_deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_org_email_idx ON users(organisation_id, lower(email));

CREATE TABLE IF NOT EXISTS user_roles (
    user_id uuid NOT NULL REFERENCES users(id),
    role_id smallint NOT NULL REFERENCES roles(id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL REFERENCES users(id),
    token_hash bytea NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS auth_sessions_user_expiry_idx ON auth_sessions(user_id, expires_at) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS login_attempts (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    login_key_hash bytea NOT NULL,
    attempted_at timestamptz NOT NULL DEFAULT now(),
    succeeded boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS login_attempts_key_time_idx ON login_attempts(login_key_hash, attempted_at DESC);

CREATE TABLE IF NOT EXISTS working_hours (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    branch_id uuid NOT NULL REFERENCES branches(id),
    user_id uuid REFERENCES users(id),
    weekday smallint NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    opens_at time NOT NULL,
    closes_at time NOT NULL,
    CHECK (closes_at > opens_at)
);

CREATE TABLE IF NOT EXISTS holidays (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    branch_id uuid NOT NULL REFERENCES branches(id),
    user_id uuid REFERENCES users(id),
    holiday_date date NOT NULL,
    reason text NOT NULL DEFAULT '',
    UNIQUE (branch_id, user_id, holiday_date)
);

CREATE SEQUENCE IF NOT EXISTS patient_public_id_seq;
CREATE TABLE IF NOT EXISTS patients (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    patient_number text NOT NULL UNIQUE DEFAULT ('PT-' || lpad(nextval('patient_public_id_seq')::text, 6, '0')),
    organisation_id uuid NOT NULL REFERENCES organisations(id),
    full_name text NOT NULL,
    email text,
    id_proof_type text,
    id_proof_encrypted bytea,
    date_of_birth date,
    gender text,
    occupation text,
    preferred_language text NOT NULL DEFAULT 'en',
    referral_source text,
    pregnancy_status text NOT NULL DEFAULT 'not_recorded'
        CHECK (pregnancy_status IN ('not_recorded','not_applicable','no','yes','prefer_not_to_say')),
    photo_document_id uuid,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive','merged','deceased')),
    search_vector tsvector GENERATED ALWAYS AS (
        to_tsvector('simple', coalesce(full_name,'') || ' ' || coalesce(email,''))
    ) STORED,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    soft_deleted_at timestamptz
);
CREATE INDEX IF NOT EXISTS patients_search_gin_idx ON patients USING gin(search_vector);
CREATE INDEX IF NOT EXISTS patients_name_trgm_idx ON patients USING gin(full_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS patients_org_created_idx ON patients(organisation_id, created_at DESC);

