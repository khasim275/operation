BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_dentist_no_overlap') THEN
        ALTER TABLE appointments ADD CONSTRAINT appointments_dentist_no_overlap
            EXCLUDE USING gist (dentist_id WITH =, tstzrange(start_at, end_at, '[)') WITH &&)
            WHERE (dentist_id IS NOT NULL AND start_at IS NOT NULL AND status IN ('confirmed','rescheduled','checked_in'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'appointments_room_no_overlap') THEN
        ALTER TABLE appointments ADD CONSTRAINT appointments_room_no_overlap
            EXCLUDE USING gist (room_id WITH =, tstzrange(start_at, end_at, '[)') WITH &&)
            WHERE (room_id IS NOT NULL AND start_at IS NOT NULL AND status IN ('confirmed','rescheduled','checked_in'));
    END IF;
END;
$$;

