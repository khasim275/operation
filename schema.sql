CREATE UNIQUE INDEX IF NOT EXISTS patient_primary_phone_idx ON patient_phones(patient_id) WHERE is_primary;
CREATE INDEX IF NOT EXISTS patient_phone_lookup_idx ON patient_phones(phone_e164);

