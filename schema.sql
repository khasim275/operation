CREATE OR REPLACE FUNCTION protect_append_only_history()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('UPDATE','DELETE') THEN
        RAISE EXCEPTION '% is append-only; add a correction/status event instead', TG_TABLE_NAME;
    END IF;
    RETURN NEW;
END;
$$;

