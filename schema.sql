$$;

CREATE OR REPLACE FUNCTION protect_consent_withdrawal()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE'
       OR OLD.withdrawn_at IS NOT NULL
       OR NEW.withdrawn_at IS NULL
       OR (to_jsonb(NEW) - 'withdrawn_at') IS DISTINCT FROM (to_jsonb(OLD) - 'withdrawn_at') THEN
        RAISE EXCEPTION 'consent records are immutable except for one withdrawal timestamp';
    END IF;
    RETURN NEW;
END;
$$;

