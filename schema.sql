CREATE SEQUENCE IF NOT EXISTS ticket_public_id_seq;
CREATE TABLE IF NOT EXISTS appointments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    ticket_number text NOT NULL UNIQUE DEFAULT ('TK-' || lpad(nextval('ticket_public_id_seq')::text, 4, '0')),
    patient_id uuid NOT NULL REFERENCES patients(id),
    branch_id uuid NOT NULL REFERENCES branches(id),
    dentist_id uuid REFERENCES users(id),
    room_id uuid REFERENCES rooms(id),
    created_by uuid REFERENCES users(id),
    source text NOT NULL DEFAULT 'whatsapp' CHECK (source IN ('whatsapp','website','walk_in','phone','referral')),
    reason text NOT NULL,
    preferred_date date,
    preferred_time_of_day text NOT NULL DEFAULT 'any'
        CHECK (preferred_time_of_day IN ('morning','afternoon','evening','any')),
    start_at timestamptz,
    end_at timestamptz,
    status text NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested','confirmed','rescheduled','checked_in','completed','cancelled','no_show')),
    status_note text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    soft_deleted_at timestamptz,
    CHECK (
        (start_at IS NULL AND end_at IS NULL)
        OR (start_at IS NOT NULL AND end_at IS NOT NULL AND end_at > start_at)
    )
);
CREATE INDEX IF NOT EXISTS appointments_queue_idx ON appointments(branch_id, created_at DESC) WHERE status = 'requested';
CREATE INDEX IF NOT EXISTS appointments_patient_date_idx ON appointments(patient_id, start_at DESC);
